//! Regenerates `src/syntax_kind/generated.rs` from `keywords.csv` and
//! `extra_keywords.csv`, and fails when the committed file was stale.

use std::fmt::Write as _;
use std::path::Path;

#[test]
fn keywords_are_fresh() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut words = read_csv(&dir.join("keywords.csv"));
    words.extend(read_csv(&dir.join("extra_keywords.csv")));
    words.sort();
    for pair in words.windows(2) {
        assert_ne!(pair[0].0, pair[1].0, "keyword listed twice");
    }
    let code = generate(&words);
    let path = dir.join("src/syntax_kind/generated.rs");
    let old = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    if old != code {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &code).unwrap();
        panic!(
            "{} was stale and has been regenerated; run the tests again",
            path.display()
        );
    }
}

fn read_csv(path: &Path) -> Vec<(String, String)> {
    let text = std::fs::read_to_string(path).unwrap();
    text.lines()
        .skip(1)
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .map(|line| {
            let (word, category) = line.split_once(',').expect("word,category");
            (word.to_ascii_lowercase(), category.to_string())
        })
        .collect()
}

fn camel(word: &str) -> String {
    word.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn category(name: &str) -> &'static str {
    match name {
        "reserved" => "Reserved",
        "unreserved" => "Unreserved",
        "type_function" => "TypeFunction",
        "column_name" => "ColumnName",
        "contextual" => "Contextual",
        other => panic!("unknown keyword category {other}"),
    }
}

fn generate(words: &[(String, String)]) -> String {
    let n = words.len();
    let mut out = String::new();
    out.push_str(
        "//! Generated by `tests/sourcegen.rs` from `keywords.csv` and\n\
         //! `extra_keywords.csv`. Edit those and run `cargo test -p diver_sql`.\n\n\
         use super::{KW_BASE, KwCategory, SyntaxKind};\n\n\
         /// A keyword of DuckDB 1.5.6, or a word the grammar treats as one.\n\
         #[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]\n\
         #[repr(u16)]\n\
         pub enum Kw {\n",
    );
    for (word, _) in words {
        writeln!(out, "    {},", camel(word)).unwrap();
    }
    out.push_str("}\n\n");
    writeln!(out, "pub(super) const KW_COUNT: usize = {n};\n").unwrap();
    writeln!(out, "pub(super) static KW_ALL: [Kw; KW_COUNT] = [").unwrap();
    for (word, _) in words {
        writeln!(out, "    Kw::{},", camel(word)).unwrap();
    }
    out.push_str("];\n\n");
    out.push_str("pub(super) static KW_TEXT: [&str; KW_COUNT] = [\n");
    for (word, _) in words {
        writeln!(out, "    {word:?},").unwrap();
    }
    out.push_str("];\n\n");
    out.push_str("pub(super) static KW_CATEGORY: [KwCategory; KW_COUNT] = [\n");
    for (_, cat) in words {
        writeln!(out, "    KwCategory::{},", category(cat)).unwrap();
    }
    out.push_str("];\n\n");
    out.push_str("pub(super) static KW_KIND_NAMES: [&str; KW_COUNT] = [\n");
    for (word, _) in words {
        writeln!(out, "    \"{}_KW\",", word.to_ascii_uppercase()).unwrap();
    }
    out.push_str("];\n\n");
    let mut by_len: Vec<&(String, String)> = words.iter().collect();
    by_len.sort_by(|a, b| (a.0.len(), &a.0).cmp(&(b.0.len(), &b.0)));
    out.push_str("/// Sorted by length, then text, for `Kw::lookup`.\n");
    out.push_str("pub(super) static KW_BY_LEN: [(&str, Kw); KW_COUNT] = [\n");
    for (word, _) in by_len {
        writeln!(out, "    ({word:?}, Kw::{}),", camel(word)).unwrap();
    }
    out.push_str("];\n\n");
    out.push_str("#[allow(clippy::identity_op)]\nimpl SyntaxKind {\n");
    for (i, (word, _)) in words.iter().enumerate() {
        writeln!(
            out,
            "    pub const {}_KW: SyntaxKind = SyntaxKind(KW_BASE + {i});",
            word.to_ascii_uppercase()
        )
        .unwrap();
    }
    out.push_str("}\n");
    out
}
